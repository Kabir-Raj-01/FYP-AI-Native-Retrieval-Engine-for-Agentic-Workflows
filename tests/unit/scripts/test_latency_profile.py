def ticking(step_s: float) -> Iterator[float]:
    t = 0.0
    while True:
        yield t
        t += step_s


@pytest.fixture
def parts(cfg: EngineConfig, tmp_state_db: Path, mini_corpus: list[CorpusChunk]) -> Parts:
    cfg.paths.state_db = tmp_state_db
    conn = connect(tmp_state_db)
    for i in range(len(QUERIES)):
        add_task(conn, lp.profile_task_id(i))
    embedder = FakeEmbedder()
    return cfg, FakeRetriever(mini_corpus, embedder=embedder), embedder, TaskCache(cfg, embedder)


Parts = tuple[EngineConfig, FakeRetriever, FakeEmbedder, TaskCache]
QUERIES = ["Linden Bay tram", "Calder Freight cargo", "KX-41 drone", "Elsmoor apricots"]


def test_measures_every_measurable_action_once_per_query(parts: Parts) -> None:
    cfg, retriever, embedder, cache = parts
    clock = ticking(0.010)
    timings = lp.measure(cfg, QUERIES, retriever, embedder, cache, clock=lambda: next(clock))
    assert set(timings) == set(lp.MEASURED)
    assert all(len(v) == len(QUERIES) for v in timings.values())
    assert all(v == pytest.approx(10.0) for vs in timings.values() for v in vs)
    deep = min(cfg.retrieval.default_k + cfg.retrieval.expand_step_k, cfg.retrieval.max_k)
    ks = [(r.mode.value, r.k) for r in retriever.requests]
    assert ("hybrid", cfg.retrieval.default_k) in ks
    assert ("dense", deep) in ks


def test_reuse_timings_are_exact_cache_hits(parts: Parts) -> None:
    cfg, retriever, embedder, cache = parts
    clock = ticking(0.001)
    lp.measure(cfg, QUERIES, retriever, embedder, cache, clock=lambda: next(clock))
    for i, q in enumerate(QUERIES):
        hit = cache.lookup(lp.profile_task_id(i), q, NeedType.SEMANTIC)
        assert hit is not None and hit.match == "exact"


def test_profile_uses_medians_and_keeps_the_transform_default(cfg: EngineConfig) -> None:
    timings = {a: [1.0, 3.0, 2.0] for a in lp.MEASURED}
    profile = lp.build_profile(cfg, timings, {"queries": 3})
    assert profile["queries"] == 3
    assert set(profile["latency_ms"]) == set(lp.ACTIONS)  # same keys as default_latency_ms
    assert all(profile["latency_ms"][a] == 2.0 for a in lp.MEASURED)
    assert profile["latency_ms"]["TRANSFORM"] == cfg.controller.default_latency_ms.TRANSFORM
    assert profile["source"] == {**dict.fromkeys(lp.MEASURED, "measured"), "TRANSFORM": "default"}
    assert "TRANSFORM" not in profile["p90_ms"]


def test_written_file_round_trips_with_lf_and_header(tmp_path: Path, cfg: EngineConfig) -> None:
    profile = lp.build_profile(cfg, {a: [5.0] for a in lp.MEASURED}, {"queries": 1})
    out = tmp_path / "configs" / "latency_profile.yaml"
    lp.write_profile(profile, out)
    data = out.read_bytes()
    assert data.startswith(b"# Generated by scripts/latency_profile.py")
    assert b"\r\n" not in data
    assert yaml.safe_load(data.decode("utf-8")) == profile


def test_main_reports_a_missing_backend(
    monkeypatch: pytest.MonkeyPatch, cfg: EngineConfig, capsys: pytest.CaptureFixture[str]
) -> None:
    class Down:
        def health(self) -> bool:
            return False

    monkeypatch.setattr(lp, "load_config", lambda path: cfg)
    monkeypatch.setattr(lp, "dev_subset_questions", lambda c, n: QUERIES)
    monkeypatch.setattr(lp.factory, "build_embedder", lambda c: FakeEmbedder())
    monkeypatch.setattr(lp.factory, "build_sparse_encoder", lambda c: None)
    monkeypatch.setattr(lp.factory, "build_retriever", lambda c, e, s: Down())
    assert lp.main([]) == 1
    assert "not reachable" in capsys.readouterr().err
